const fs=require('fs'),vm=require('vm'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const ui=fs.readFileSync(path.join(root,'js/ui.js'),'utf8');
const match=ui.match(/const CODEX_SEARCH_TEXT_CACHE_LIMIT = 4096;\s*const CODEX_SEARCH_TEXT_CACHE = new Map\(\);\s*function getCodexSearchText\(row\) \{[\s\S]*?\n\}/);
assert(match,'codex search helper is present');
const ctx={Map,ITEMS:{fireworks_card:{name:'煙火卡片',imgId:300640,type:'material'}},CARDS:{fireworks_card:{name:'煙火卡片',imgId:300640,slot:'footgear'}},MONSTERS:{}};
vm.createContext(ctx);vm.runInContext(match[0],ctx);
const text=vm.runInContext("getCodexSearchText({id:'fireworks_card',name:'煙火卡片'})",ctx);
assert(text.includes('300640'),'official item ID is indexed');
assert(text.includes('fireworks_card'),'internal card ID remains searchable');
assert(text.includes('煙火卡片'),'localized card name remains searchable');
assert(text.includes('footgear'),'card slot remains searchable');
const itemCtx={Map,ITEMS:{test_item:{name:'測試道具',imgId:987654,searchTerms:'別名'}},CARDS:{},MONSTERS:{}};
vm.createContext(itemCtx);vm.runInContext(match[0],itemCtx);
const itemText=vm.runInContext("getCodexSearchText({id:'test_item',name:'測試道具'})",itemCtx);
assert(itemText.includes('987654')&&itemText.includes('別名'),'ordinary item official ID and aliases are indexed');
console.log('PASS card official numeric ID search');
console.log('PASS internal ID, name, slot, item ID and aliases remain searchable');
console.log('2/2 passed');
