const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const skillsText = fs.readFileSync('js/skills.js','utf8');
const ctx = {};
vm.createContext(ctx);
vm.runInContext(skillsText + ';globalThis.__skills=SKILLS;',ctx);
const s=ctx.__skills;
assert(s.cloudkill && s.hellinferno && s.fireball, 'Smoky LT proc skill bodies are registered');
assert.strictEqual(s.hellinferno.maxLv,5,'Hell Inferno skill level cap is represented');
assert.strictEqual(s.fireball.maxLv,10,'Fire Ball supports equipment-triggered Lv9');
console.log('v2.5.199 Smoky LT skill registry regression: 4/4 passed');
