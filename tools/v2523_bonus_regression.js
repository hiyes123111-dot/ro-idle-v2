const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const src = fs.readFileSync('js/engine.js', 'utf8');
const start = src.indexOf('function canonicalBonusKey(key)');
const end = src.indexOf('/* 全身裝備提供的加成總表', start);
assert(start >= 0 && end > start, 'bonus normalization functions exist');
const snippet = src.slice(start, end);
const ctx = {};
vm.runInNewContext(snippet + '\nthis.canonicalBonusKey = canonicalBonusKey; this.mergeBonus = mergeBonus;', ctx);
assert.strictEqual(ctx.canonicalBonusKey('patk'), 'pAtk');
assert.strictEqual(ctx.canonicalBonusKey('smatk'), 'sMatk');
assert.strictEqual(ctx.canonicalBonusKey('perBaseLv210_patk'), 'perBaseLv210_pAtk');
assert.strictEqual(ctx.canonicalBonusKey('perJobLv10_smatk'), 'perJobLv10_sMatk');
const merged = {};
ctx.mergeBonus(merged, { patk: 20, pAtk: 2, smatk: 10, sMatk: 3 });
assert.deepStrictEqual(JSON.parse(JSON.stringify(merged)), { pAtk: 22, sMatk: 13 });
console.log('PASS legacy and canonical P.ATK / S.MATK keys merge without loss');
const data = fs.readFileSync('js/data.js', 'utf8');
assert(data.includes('"patk":20') || data.includes('"patk": 20'), 'legacy lowercase patk item data remains present for regression');
assert(src.includes("getCardBonus('pAtk')"), 'physical damage consumes normalized P.ATK');
assert(src.includes("getCardBonus('sMatk')"), 'magic damage consumes normalized S.MATK');
console.log('PASS P.ATK and S.MATK damage consumers are wired');
