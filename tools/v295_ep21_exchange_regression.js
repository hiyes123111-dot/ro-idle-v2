const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const data = fs.readFileSync(path.join(root, 'js/data.js'), 'utf8');
const engine = fs.readFileSync(path.join(root, 'js/engine.js'), 'utf8');
const ui = fs.readFileSync(path.join(root, 'js/ui.js'), 'utf8');
const cardIds = ['ep21_tris_card','ep21_tan_borg_card','ep21_bihailin_card','ep21_reinhardt_card','ep21_evan_wigner_card','ep21_lalila_card','ep21_richard_card','ep21_lora_card','ep21_aurely_card','ep21_ylze_card','ep21_epesto_card','ep21_mary_stella_card','ep21_john_card','ep21_kunt_card','ep21_galacia_card','ep21_iana_card','ep21_lee_card','ep21_nadoyou_card'];
const fragIds = Array.from({length:18},(_,i)=>1001837+i);
for (const id of cardIds) if (!data.includes("'"+id+"':")) throw new Error('Missing card item '+id);
for (const id of fragIds) if (!data.includes('imgId:'+id+',')) throw new Error('Missing official fragment item ID '+id);
if (!engine.includes('const EP21_CARD_EXCHANGE_RECIPES')) throw new Error('Exchange recipes missing');
if (!engine.includes("fragmentRow.qty < 30")) throw new Error('Exchange does not enforce 30 fragments');
if (!engine.includes("removeItem(recipe.fragment, 30)")) throw new Error('Exchange does not consume 30 fragments');
if (!engine.includes('ep21ExchangeBusy')) throw new Error('Exchange re-entry lock missing');
if (!ui.includes('魏格納商隊兌換員') || !ui.includes('openEp21WignerExchange')) throw new Error('NPC UI missing');
const itemBlock = data.slice(data.indexOf('const ITEMS ='), data.indexOf('const MONSTER_FAMILIES ='));
const ep21CardLines = itemBlock.split(/\r?\n/).filter(x=>/^\s*'ep21_[^']+_card':/.test(x));
if (ep21CardLines.length !== 18) throw new Error('Expected 18 EP21 card item rows, got '+ep21CardLines.length);
console.log('PASS: 18 cards, 18 official fragment IDs (1001837–1001854), 30:1 recipes, inventory check, consume, lock, town NPC UI');
