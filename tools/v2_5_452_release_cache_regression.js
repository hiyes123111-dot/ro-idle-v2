const fs=require('fs'),path=require('path'),assert=require('assert');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const version=fs.readFileSync(path.join(root,'VERSION.txt'),'utf8').trim();
assert.strictEqual(version,'2.5.452','VERSION.txt matches release');
assert(sw.includes("ro-idle-runtime-v2.5.452"),'service worker runtime cache version matches release');
const refs=[...html.matchAll(/(?:src|href)=["'][^"']+\?v=([^"']+)["']/g)].map(m=>m[1]);
assert(refs.length>0,'versioned assets exist');
assert(refs.every(v=>v==='2.5.452'),'all CSS/JS cache-busting query versions match release');
assert(html.includes('js/v2_5_452_card_catalog_cleanup.js?v=2.5.452'),'card search patch is loaded');
assert(!html.includes('2.5.451'),'index contains no stale release references');
console.log(JSON.stringify({passed:6,version,versionedAssets:refs.length,checks:['VERSION.txt','service worker cache','all cache-busting URLs','catalog patch included','no stale 451 references']},null,2));
